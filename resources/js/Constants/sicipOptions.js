/**
 * Returns relevant subjects matching the selected educational degree/qualification.
 */
export function getSubjectsForDegree(degree) {
  if (!degree) return ALL_EDUCATION_SUBJECTS;
  const d = degree.toLowerCase();

  // Secondary
  if (d.includes('এসএসসি') || d.includes('ssc') || d.includes('দাখিল') || d.includes('dakhil') || d.includes('ও-লেভেল') || d.includes('o-level') || d.includes('জেএসসি') || d.includes('jsc') || d.includes('অষ্টম')) {
    return SUBJECTS_SECONDARY;
  }
  // Higher Secondary
  if (d.includes('এইচএসসি') || d.includes('hsc') || d.includes('আলিম') || d.includes('alim') || d.includes('এ-লেভেল') || d.includes('a-level') || d.includes('বিএমটি')) {
    return SUBJECTS_HIGHER_SECONDARY;
  }
  // Diploma / Technical
  if (d.includes('ডিপ্লোমা') || d.includes('diploma') || d.includes('পলিটেকনিক') || d.includes('কারিগরি') || d.includes('ভোকেশনাল') || d.includes('pgd')) {
    return SUBJECTS_DIPLOMA;
  }
  // Business / BBA / MBA / Commerce
  if (d.includes('বিবিএ') || d.includes('bba') || d.includes('এমবিএ') || d.includes('mba') || d.includes('বিকম') || d.includes('b.com') || d.includes('এমকম') || d.includes('m.com') || d.includes('বিবিএস') || d.includes('bbs') || d.includes('এমবিএস') || d.includes('ব্যবসা') || d.includes('business')) {
    return SUBJECTS_BUSINESS;
  }
  // Engineering / Tech / IT
  if (d.includes('ইঞ্জিনিয়ারিং') || d.includes('engineering') || d.includes('cse') || d.includes('eee') || d.includes('civil') || d.includes('mechanical') || d.includes('সফটওয়্যার') || d.includes('টেক্সটাইল')) {
    return SUBJECTS_ENGINEERING;
  }
  // Law
  if (d.includes('আইন') || d.includes('law') || d.includes('llb') || d.includes('ll.b') || d.includes('llm') || d.includes('ll.m')) {
    return SUBJECTS_LAW;
  }
  // Medical / Healthcare
  if (d.includes('এমবিবিএস') || d.includes('mbbs') || d.includes('বিডিএস') || d.includes('bds') || d.includes('ফার্ম') || d.includes('pharm') || d.includes('নার্সিং') || d.includes('nursing') || d.includes('মেডিকেল') || d.includes('mph') || d.includes('fcps')) {
    return SUBJECTS_MEDICAL;
  }
  // Agriculture / Veterinary
  if (d.includes('কৃষি') || d.includes('agri') || d.includes('dvm') || d.includes('ভেটেরিনারি') || d.includes('প্রাণিসম্পদ')) {
    return SUBJECTS_AGRICULTURE;
  }
  // Social Science
  if (d.includes('বিএসএস') || d.includes('bss') || d.includes('এমএসএস') || d.includes('mss') || d.includes('সমাজবিজ্ঞান') || d.includes('social')) {
    return SUBJECTS_SOCIAL_SCIENCE;
  }
  // Arts & Humanities
  if (d.includes('বিএ') || d.includes('ba hons') || d.includes('এমএ') || d.includes('ma ') || d.includes('কলা') || d.includes('arts') || d.includes('মানবিক') || d.includes('ফাজিল') || d.includes('কামিল')) {
    return SUBJECTS_ARTS;
  }
  // Science
  if (d.includes('বিএসসি') || d.includes('b.sc') || d.includes('এমএসসি') || d.includes('m.sc') || d.includes('বিজ্ঞান')) {
    return SUBJECTS_SCIENCE;
  }

  return ALL_EDUCATION_SUBJECTS;
}

